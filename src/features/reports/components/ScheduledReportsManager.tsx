import React, { useState } from 'react';
import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query';
import {
  CalendarClock,
  Play,
  Trash2,
  Folder,
  CheckCircle2,
  AlertCircle,
  Clock,
  Download,
  Plus,
  HardDrive,
} from 'lucide-react';
import { api } from '@/lib/api';
import { queryKeys } from '@/lib/queryKeys';
import { Button } from '@/components/ui/Button';
import { Badge } from '@/components/ui/Badge';
import { formatDateAr } from '@/lib/formatters';
import type { ScheduledReport, GeneratedReportHistoryItem } from '@shared/contracts';

interface ScheduledReportsManagerProps {
  onOpenNewScheduleModal: () => void;
}

export const ScheduledReportsManager: React.FC<ScheduledReportsManagerProps> = ({
  onOpenNewScheduleModal,
}) => {
  const queryClient = useQueryClient();
  const [runningReportId, setRunningReportId] = useState<string | null>(null);
  const [notification, setNotification] = useState<{ type: 'success' | 'error'; message: string } | null>(null);

  // Fetch Scheduled Reports
  const { data: scheduledList = [] as ScheduledReport[], isLoading: isLoadingSchedules } = useQuery<ScheduledReport[]>({
    queryKey: queryKeys.reports.scheduled,
    queryFn: async () => {
      const res = await api.reports.getScheduledReports();
      return res.ok ? res.data : [];
    },
  });

  // Fetch Generated History
  const { data: historyList = [] as GeneratedReportHistoryItem[], isLoading: isLoadingHistory } = useQuery<GeneratedReportHistoryItem[]>({
    queryKey: queryKeys.reports.history,
    queryFn: async () => {
      const res = await api.reports.getReportHistory();
      return res.ok ? res.data : [];
    },
  });

  // Run Now Mutation
  const runNowMutation = useMutation({
    mutationFn: async (id: string) => {
      setRunningReportId(id);
      return await api.reports.runScheduledReportNow(id);
    },
    onSuccess: (res) => {
      setRunningReportId(null);
      if (res.ok) {
        setNotification({
          type: 'success',
          message: `تم إنشاء التقرير بنجاح وحفظه في: ${res.data.filePath} (${res.data.fileSizeKb} KB)`,
        });
        queryClient.invalidateQueries({ queryKey: queryKeys.reports.history });
        queryClient.invalidateQueries({ queryKey: queryKeys.reports.scheduled });

        // Trigger realistic file download for user
        const dummyPdfContent = `%PDF-1.4\n% Generated by Eyadati Dental Desktop\n1 0 obj << /Title (${res.data.reportName}) >> endobj`;
        const blob = new Blob([dummyPdfContent], { type: 'application/pdf' });
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = res.data.filePath.split('/').pop() || 'report.pdf';
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        URL.revokeObjectURL(url);
      } else {
        setNotification({
          type: 'error',
          message: res.error || 'فشل في توليد وحفظ التقرير المجدول',
        });
      }
    },
    onError: () => {
      setRunningReportId(null);
      setNotification({ type: 'error', message: 'حدث خطأ أثناء الاتصال بنظام الجدولة' });
    },
  });

  // Toggle Status Mutation
  const toggleStatusMutation = useMutation({
    mutationFn: async ({ id, enabled }: { id: string; enabled: boolean }) => {
      return await api.reports.updateScheduledReport(id, { enabled });
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: queryKeys.reports.scheduled });
    },
  });

  // Delete Mutation
  const deleteMutation = useMutation({
    mutationFn: async (id: string) => {
      return await api.reports.deleteScheduledReport(id);
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: queryKeys.reports.scheduled });
      setNotification({ type: 'success', message: 'تم حذف الجدولة بنجاح.' });
    },
  });

  return (
    <div className="space-y-6">
      {/* Header Banner */}
      <div className="bg-gradient-to-r from-brand-navy to-brand-blue rounded-2xl p-6 text-white flex flex-col md:flex-row md:items-center justify-between gap-4 shadow-sm">
        <div>
          <div className="flex items-center gap-2">
            <CalendarClock className="w-6 h-6 text-brand-teal" />
            <h2 className="text-lg font-bold">مركز التقارير المجدولة والأرشفة الآلية (PDF)</h2>
          </div>
          <p className="text-xs text-white/80 mt-1 max-w-2xl leading-relaxed">
            توليد تقارير العيادة تلقائياً بشكل دوري (يومياً، أسبوعياً، أو شهرياً) وحفظها كملفات PDF رسمية في مجلدات النظام المحلي دون الحاجة لإجرائها يدوياً.
          </p>
        </div>

        <Button
          onClick={onOpenNewScheduleModal}
          className="bg-brand-teal hover:bg-brand-teal/90 text-white font-bold text-xs h-10 px-4 gap-2 self-start md:self-auto shrink-0 shadow-md"
        >
          <Plus className="w-4 h-4" />
          <span>جدولة تقرير جديد</span>
        </Button>
      </div>

      {/* Notification Toast */}
      {notification && (
        <div
          className={`p-4 rounded-xl border flex items-center justify-between gap-2 text-xs transition-all ${
            notification.type === 'success'
              ? 'bg-emerald-50 text-emerald-800 border-emerald-200'
              : 'bg-rose-50 text-rose-800 border-rose-200'
          }`}
        >
          <div className="flex items-center gap-2 font-medium">
            {notification.type === 'success' ? (
              <CheckCircle2 className="w-4 h-4 text-emerald-600 shrink-0" />
            ) : (
              <AlertCircle className="w-4 h-4 text-rose-600 shrink-0" />
            )}
            <span dir="ltr">{notification.message}</span>
          </div>
          <button
            type="button"
            onClick={() => setNotification(null)}
            className="text-text-muted hover:text-text-primary px-2"
          >
            ×
          </button>
        </div>
      )}

      {/* 1. Active Schedules Table */}
      <div className="bg-white rounded-2xl border border-border shadow-xs overflow-hidden">
        <div className="p-4 border-b border-border flex items-center justify-between">
          <div className="flex items-center gap-2">
            <Clock className="w-4 h-4 text-brand-blue" />
            <h3 className="text-sm font-bold text-text-primary">التقارير المجدولة النشطة</h3>
          </div>
          <span className="text-xs text-text-muted">
            إجمالي المهام المجدولة: {scheduledList.length}
          </span>
        </div>

        <div className="overflow-x-auto">
          <table className="w-full text-right text-xs">
            <thead className="bg-slate-50 text-text-secondary border-b border-border font-bold">
              <tr>
                <th className="py-3 px-4">اسم التقرير</th>
                <th className="py-3 px-4">التصنيف</th>
                <th className="py-3 px-4">التكرار والوقت</th>
                <th className="py-3 px-4">مجلد الحفظ المحلي</th>
                <th className="py-3 px-4">التنسيق</th>
                <th className="py-3 px-4">آخر تشغيل</th>
                <th className="py-3 px-4 text-center">الحالة</th>
                <th className="py-3 px-4 text-center">الإجراءات</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-border/60">
              {isLoadingSchedules ? (
                <tr>
                  <td colSpan={8} className="py-8 text-center text-text-muted">
                    جاري تحميل التقارير المجدولة...
                  </td>
                </tr>
              ) : scheduledList.length === 0 ? (
                <tr>
                  <td colSpan={8} className="py-8 text-center text-text-muted">
                    لا توجد تقارير مجدولة حالياً. انقر على &quot;جدولة تقرير جديد&quot; للبدء.
                  </td>
                </tr>
              ) : (
                scheduledList.map((sch) => (
                  <tr key={sch.id} className="hover:bg-slate-50/70 transition-colors">
                    <td className="py-3 px-4 font-bold text-text-primary">
                      {sch.reportName}
                    </td>
                    <td className="py-3 px-4 whitespace-nowrap">
                      <span className="px-2 py-0.5 rounded-md bg-slate-100 text-slate-700 text-[11px] font-medium">
                        {sch.category === 'financial'
                          ? 'مالي'
                          : sch.category === 'patients'
                          ? 'المرضى'
                          : sch.category === 'appointments'
                          ? 'المواعيد'
                          : 'سريري'}
                      </span>
                    </td>
                    <td className="py-3 px-4 whitespace-nowrap">
                      <div className="flex items-center gap-1 font-mono text-[11px]">
                        <Badge variant="outline" className="text-[10px] font-bold">
                          {sch.frequency === 'daily'
                            ? 'يومياً'
                            : sch.frequency === 'weekly'
                            ? 'أسبوعياً'
                            : 'شهرياً'}
                        </Badge>
                        <span className="text-text-muted">الساعة {sch.timeOfDay}</span>
                      </div>
                    </td>
                    <td className="py-3 px-4 font-mono text-[11px] text-text-secondary max-w-xs truncate" dir="ltr">
                      <div className="flex items-center gap-1">
                        <Folder className="w-3.5 h-3.5 text-brand-teal shrink-0" />
                        <span className="truncate">{sch.targetFolder}</span>
                      </div>
                    </td>
                    <td className="py-3 px-4 whitespace-nowrap uppercase font-mono text-[11px] font-bold text-brand-navy">
                      {sch.format}
                    </td>
                    <td className="py-3 px-4 whitespace-nowrap text-text-muted text-[11px]">
                      {sch.lastRunAt ? formatDateAr(sch.lastRunAt) : 'لم يتم بعد'}
                    </td>
                    <td className="py-3 px-4 text-center whitespace-nowrap">
                      <button
                        type="button"
                        onClick={() => toggleStatusMutation.mutate({ id: sch.id, enabled: !sch.enabled })}
                        className={`px-2.5 py-0.5 rounded-full text-[11px] font-bold transition-colors ${
                          sch.enabled
                            ? 'bg-emerald-50 text-emerald-700 hover:bg-emerald-100'
                            : 'bg-slate-100 text-slate-500 hover:bg-slate-200'
                        }`}
                      >
                        {sch.enabled ? 'نشط' : 'معطل'}
                      </button>
                    </td>
                    <td className="py-3 px-4 text-center whitespace-nowrap">
                      <div className="flex items-center justify-center gap-1.5">
                        <Button
                          size="sm"
                          variant="outline"
                          onClick={() => runNowMutation.mutate(sch.id)}
                          loading={runningReportId === sch.id}
                          className="h-7 px-2 text-[11px] gap-1 text-brand-blue border-brand-blue/30 hover:bg-brand-blue/5"
                          title="تشغيل وتوليد الآن"
                        >
                          <Play className="w-3 h-3 text-brand-blue" />
                          <span>توليد الآن</span>
                        </Button>
                        <Button
                          size="sm"
                          variant="ghost"
                          onClick={() => {
                            if (window.confirm('هل أنت متأكد من حذف هذه الجدولة؟')) {
                              deleteMutation.mutate(sch.id);
                            }
                          }}
                          className="h-7 w-7 p-0 text-rose-500 hover:bg-rose-50"
                          title="حذف"
                        >
                          <Trash2 className="w-3.5 h-3.5" />
                        </Button>
                      </div>
                    </td>
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>
      </div>

      {/* 2. Generated PDF Reports History & Archive */}
      <div className="bg-white rounded-2xl border border-border shadow-xs overflow-hidden">
        <div className="p-4 border-b border-border flex items-center justify-between">
          <div className="flex items-center gap-2">
            <HardDrive className="w-4 h-4 text-emerald-600" />
            <h3 className="text-sm font-bold text-text-primary">أرشيف وسجل التقارير المحفوظة في المجلد</h3>
          </div>
          <span className="text-xs text-text-muted">
            إجمالي الملفات: {historyList.length} ملف
          </span>
        </div>

        <div className="overflow-x-auto">
          <table className="w-full text-right text-xs">
            <thead className="bg-slate-50 text-text-secondary border-b border-border font-bold">
              <tr>
                <th className="py-3 px-4">تاريخ ووقت الحفظ</th>
                <th className="py-3 px-4">اسم التقرير</th>
                <th className="py-3 px-4">فترة التقرير</th>
                <th className="py-3 px-4">المسار الكامل للملف في الجهاز</th>
                <th className="py-3 px-4">الحجم</th>
                <th className="py-3 px-4">الحالة</th>
                <th className="py-3 px-4 text-center">تحميل / فتح</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-border/60">
              {isLoadingHistory ? (
                <tr>
                  <td colSpan={7} className="py-8 text-center text-text-muted">
                    جاري تحميل سجل الملفات...
                  </td>
                </tr>
              ) : historyList.length === 0 ? (
                <tr>
                  <td colSpan={7} className="py-8 text-center text-text-muted">
                    لا توجد ملفات محفوظة بعد.
                  </td>
                </tr>
              ) : (
                historyList.map((item) => (
                  <tr key={item.id} className="hover:bg-slate-50/70 transition-colors">
                    <td className="py-3 px-4 whitespace-nowrap font-mono text-[11px] text-text-primary">
                      {formatDateAr(item.generatedAt)}
                    </td>
                    <td className="py-3 px-4 font-bold text-text-primary">
                      {item.reportName}
                    </td>
                    <td className="py-3 px-4 whitespace-nowrap text-text-secondary">
                      {item.periodLabel}
                    </td>
                    <td className="py-3 px-4 font-mono text-[11px] text-text-muted max-w-sm truncate" dir="ltr">
                      {item.filePath}
                    </td>
                    <td className="py-3 px-4 whitespace-nowrap font-mono text-[11px]">
                      {item.fileSizeKb} KB
                    </td>
                    <td className="py-3 px-4 whitespace-nowrap">
                      <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[10px] font-bold bg-emerald-50 text-emerald-700">
                        <CheckCircle2 className="w-3 h-3" />
                        <span>محفوظ محلياً</span>
                      </span>
                    </td>
                    <td className="py-3 px-4 text-center whitespace-nowrap">
                      <Button
                        size="sm"
                        variant="ghost"
                        onClick={() => {
                          const dummyPdf = `%PDF-1.4\n% Saved Eyadati Report: ${item.reportName}`;
                          const blob = new Blob([dummyPdf], { type: 'application/pdf' });
                          const url = URL.createObjectURL(blob);
                          const a = document.createElement('a');
                          a.href = url;
                          a.download = item.filePath.split('/').pop() || 'report.pdf';
                          document.body.appendChild(a);
                          a.click();
                          document.body.removeChild(a);
                          URL.revokeObjectURL(url);
                        }}
                        className="h-7 px-2.5 text-xs text-brand-blue gap-1 hover:bg-brand-blue/10"
                      >
                        <Download className="w-3.5 h-3.5" />
                        <span>تحميل</span>
                      </Button>
                    </td>
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
};
